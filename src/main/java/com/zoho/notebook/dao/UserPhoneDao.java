    public boolean resetPrimary(long userId) throws Exception {
        UpdateQueryImpl q = new UpdateQueryImpl(TableName.UserPhone.name());
        q.setUpdateColumn("IS_PRIMARY", 0);
        q.setUpdateColumn("UPDATED_AT", System.currentTimeMillis());
        q.setCriteria(new Criteria(new Column(TableName.UserPhone.name(), "USER_ID"), userId, QueryConstants.EQUAL));
        DataAccess.update(q);
        return true;
    }

    public boolean setPrimary(long userId, String phone) throws Exception {
        UpdateQueryImpl q = new UpdateQueryImpl(TableName.UserPhone.name());
        q.setUpdateColumn("IS_PRIMARY", 1);
        q.setUpdateColumn("UPDATED_AT", System.currentTimeMillis());
        Criteria c = new Criteria(new Column(TableName.UserPhone.name(), "USER_ID"),    userId, QueryConstants.EQUAL);
        c = c.and(new Criteria(new Column(TableName.UserPhone.name(), "PHONE_NUMBER"),  phone,  QueryConstants.EQUAL));
        q.setCriteria(c);
        DataAccess.update(q);
        return true;
    }

    public boolean delete(long userId, String phone) throws Exception {
        Criteria c = new Criteria(new Column(TableName.UserPhone.name(), "USER_ID"),    userId, QueryConstants.EQUAL);
        c = c.and(new Criteria(new Column(TableName.UserPhone.name(), "PHONE_NUMBER"),  phone,  QueryConstants.EQUAL));
        c = c.and(new Criteria(new Column(TableName.UserPhone.name(), "IS_PRIMARY"),    0,      QueryConstants.EQUAL));
        DataAccess.delete(c);
        return true;
    }
